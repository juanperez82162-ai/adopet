    INTO v_estado, v_vence, v_obs
    FROM SOLICITUDES_ADOPCION
   WHERE ID_SOLICITUD = P_ID_SOLICITUD
     FOR UPDATE;

  -- Solo se gestionan solicitudes ACTIVAS con fecha de vencimiento
  IF v_estado <> 2 OR v_vence IS NULL THEN
    RETURN;
