    v_patron := CASE p_estilo
      WHEN 'CODIGO'  THEN '^[A-ZÁÉÍÓÚÜÑ]+(_[A-Z0-9ÁÉÍÓÚÜÑ]+)*$'
      WHEN 'INITCAP' THEN '^[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+([ ''-][A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+)*$'
