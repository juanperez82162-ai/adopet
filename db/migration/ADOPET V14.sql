  FUNCTION normalizar_texto (p_texto    IN VARCHAR2,
                             p_colapsar IN VARCHAR2 DEFAULT 'S') RETURN VARCHAR2 IS
  BEGIN
    IF p_colapsar = 'S' THEN
      RETURN TRIM(REGEXP_REPLACE(p_texto, '\s+', ' '));
    END IF;
    RETURN TRIM(p_texto);
  END normalizar_texto;

  FUNCTION normalizar_nombre (p_nombre IN VARCHAR2,
                              p_estilo IN VARCHAR2 DEFAULT 'LIBRE') RETURN VARCHAR2 IS
    v VARCHAR2(4000) := normalizar_texto(p_nombre, 'S');
  BEGIN
    RETURN CASE p_estilo
             WHEN 'INITCAP' THEN INITCAP(v)
             WHEN 'CODIGO'  THEN UPPER(REPLACE(v, ' ', '_'))
             ELSE v                       -- LIBRE y ALFANUM: solo limpieza
           END;
  END normalizar_nombre;

  FUNCTION normalizar_sn (p_valor   IN VARCHAR2,
                          p_defecto IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
  BEGIN
    RETURN NVL(UPPER(TRIM(p_valor)), p_defecto);
  END normalizar_sn;

