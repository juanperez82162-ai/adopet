         '^[^<>"|?*]+\.(jpg|jpeg|png|webp)$', 'i') THEN
      RAISE_APPLICATION_ERROR(-20603,
        'La ruta debe terminar en .jpg, .jpeg, .png o .webp y no contener < > " | ? *.');
    END IF;

    -- 5. La mascota debe existir (activa o inactiva, no importa).
    --    FOR UPDATE bloquea su fila: evita que dos sesiones agreguen fotos
    --    a la misma mascota al mismo tiempo y se pasen del límite.
    BEGIN
      SELECT ID_MASCOTA
        INTO v_id
        FROM MASCOTAS
       WHERE ID_MASCOTA = :NEW.ID_MASCOTA
         FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20604,
          'La mascota indicada no existe o no se especificó.');
    END;

    -- 6. Anotar la mascota para contarla al final
    g_mascotas(:NEW.ID_MASCOTA) := TRUE;
  END BEFORE EACH ROW;

  -- ------------------------------------------------------------
  -- Se ejecuta una vez, cuando ya terminó el INSERT
  -- ------------------------------------------------------------
  AFTER STATEMENT IS
    v_id    PLS_INTEGER;
    v_total NUMBER;
  BEGIN
    v_id := g_mascotas.FIRST;
    WHILE v_id IS NOT NULL LOOP
      SELECT COUNT(*)
        INTO v_total
        FROM FOTOS_MASCOTAS
       WHERE ID_MASCOTA = v_id;

      IF v_total > c_max_fotos THEN
        RAISE_APPLICATION_ERROR(-20606,
          'La mascota ' || v_id || ' quedaría con ' || v_total ||
          ' fotos. El máximo permitido es ' || c_max_fotos ||
          ' (incluida la foto principal).');
      END IF;

      v_id := g_mascotas.NEXT(v_id);
    END LOOP;
  END AFTER STATEMENT;

END TRG_FOTOS_MASCOTAS_INSERT;

