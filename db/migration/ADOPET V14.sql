      ELSE
        RAISE_APPLICATION_ERROR(-20425,
          'PKG_ESTADO: la tabla "' || p_tabla || '" no se puede activar ni desactivar (no existe o es fija del sistema).');
    END CASE;
  END cargar_meta;

  PROCEDURE cambiar_estado (
    p_tabla       IN  VARCHAR2,
    p_id          IN  VARCHAR2 DEFAULT NULL,
    p_nombre      IN  VARCHAR2 DEFAULT NULL,
    p_accion      IN  VARCHAR2 DEFAULT 'ALTERNAR',
    p_observacion IN  VARCHAR2 DEFAULT NULL,
    p_mensaje     OUT VARCHAR2
  ) IS
    v_tabla   VARCHAR2(30)  := UPPER(TRIM(p_tabla));
    v_accion  VARCHAR2(20)  := UPPER(TRIM(NVL(p_accion, 'ALTERNAR')));
    v_id_in   VARCHAR2(200) := UPPER(TRIM(p_id));
    v_nom_in  VARCHAR2(200) := PKG_VALIDACIONES.normalizar_texto(p_nombre);
    v_obs     VARCHAR2(200) := PKG_VALIDACIONES.normalizar_texto(p_observacion);
    v_col_id  VARCHAR2(30);
    v_col_nom VARCHAR2(30);
    v_id      VARCHAR2(50);
    v_nombre  VARCHAR2(200);
    v_activo  CHAR(1);
    v_nuevo   CHAR(1);
    v_sql     VARCHAR2(1000);
  BEGIN
    cargar_meta(v_tabla, v_col_id, v_col_nom);

    -- 1. Validar parámetros
    IF (v_id_in IS NULL AND v_nom_in IS NULL)
       OR (v_id_in IS NOT NULL AND v_nom_in IS NOT NULL) THEN
      RAISE_APPLICATION_ERROR(-20420,
        v_tabla || ': indique el id o el nombre, pero no ambos ni ninguno.');
    END IF;

    IF v_accion NOT IN ('ALTERNAR', 'ACTIVAR', 'DESACTIVAR') THEN
      RAISE_APPLICATION_ERROR(-20421,
        v_tabla || ': la acción debe ser ALTERNAR, ACTIVAR o DESACTIVAR.');
    END IF;

    IF v_nom_in IS NOT NULL AND v_col_nom IS NULL THEN
      RAISE_APPLICATION_ERROR(-20424,
        v_tabla || ': esta tabla solo se busca por id.');
    END IF;

    -- 2. Buscar la fila y bloquearla mientras se decide
    v_sql := 'SELECT TO_CHAR(' || v_col_id || '), ' || NVL(v_col_nom, 'NULL') ||
             ', ACTIVO FROM ' || v_tabla || ' WHERE ';

    IF v_id_in IS NOT NULL THEN
      v_sql := v_sql || v_col_id || ' = :1';
    ELSE
      -- Ignora mayúsculas, espacios sobrantes y espacio vs guion bajo
      v_sql := v_sql || 'UPPER(REPLACE(TRIM(' || v_col_nom ||
               '), '' '', ''_'')) = UPPER(REPLACE(:1, '' '', ''_''))';
    END IF;

    v_sql := v_sql || ' FOR UPDATE';

    BEGIN
      EXECUTE IMMEDIATE v_sql
        INTO v_id, v_nombre, v_activo
        USING NVL(v_id_in, v_nom_in);
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20422,
          v_tabla || ': no existe un registro con ese ' ||
          CASE WHEN v_id_in IS NOT NULL THEN 'id.' ELSE 'nombre.' END);
      WHEN TOO_MANY_ROWS THEN
        RAISE_APPLICATION_ERROR(-20423,
          v_tabla || ': el nombre coincide con más de un registro; use el id.');
      WHEN INVALID_NUMBER THEN
        RAISE_APPLICATION_ERROR(-20426,
          v_tabla || ': el id "' || v_id_in || '" no tiene un formato válido.');
    END;

    v_nombre := NVL(v_nombre, v_id);   -- USUARIOS no tiene columna de nombre

    -- 3. Decidir el nuevo estado
    v_nuevo := CASE v_accion
                 WHEN 'ACTIVAR'    THEN 'S'
                 WHEN 'DESACTIVAR' THEN 'N'
                 ELSE CASE v_activo WHEN 'S' THEN 'N' ELSE 'S' END
               END;

    -- 4. Sin cambio: solo informar. Con cambio: UPDATE (aquí se dispara el trigger)
    IF v_nuevo = v_activo THEN
      p_mensaje := v_tabla || ' "' || v_nombre || '" (id ' || v_id ||
                   '): ya estaba ' ||
                   CASE v_activo WHEN 'S' THEN 'activo.' ELSE 'desactivado.' END;
    ELSE
      IF v_tabla = 'MASCOTAS' THEN
        -- CK_MASCOTA_INACTIVA exige el motivo al desactivar; al reactivar se limpia
        UPDATE MASCOTAS
           SET ACTIVO = v_nuevo,
               OBSERVACIONES_ESTADO = CASE WHEN v_nuevo = 'N' THEN v_obs END
         WHERE ID_MASCOTA = TO_NUMBER(v_id);
      ELSE
        EXECUTE IMMEDIATE
          'UPDATE ' || v_tabla || ' SET ACTIVO = :1 WHERE ' || v_col_id || ' = :2'
          USING v_nuevo, v_id;
      END IF;

      p_mensaje := v_tabla || ' "' || v_nombre || '" (id ' || v_id || '): ' ||
                   CASE v_nuevo WHEN 'N' THEN 'fue desactivado recién.'
                                         ELSE 'fue reactivado.' END;
    END IF;

    DBMS_OUTPUT.PUT_LINE(p_mensaje);
    -- Sin COMMIT: el que llama decide confirmar o deshacer.
  END cambiar_estado;

END PKG_ESTADO;

