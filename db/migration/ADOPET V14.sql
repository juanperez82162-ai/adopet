  AFTER EACH ROW IS
  BEGIN
    IF NVL(REGEXP_COUNT(:NEW.OBSERVACIONES, 'CONTACTO REGISTRADO:', 1, 'i'), 0)
     > NVL(REGEXP_COUNT(:OLD.OBSERVACIONES, 'CONTACTO REGISTRADO:', 1, 'i'), 0) THEN
      g_ids(g_ids.COUNT + 1) := :NEW.ID_SOLICITUD;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    FOR i IN 1 .. g_ids.COUNT LOOP
      PR_GESTIONAR_CONTACTO_SOLICITUD(g_ids(i));
    END LOOP;
  END AFTER STATEMENT;

