  IF :NEW.CORREO IS NULL
     OR NOT REGEXP_LIKE(:NEW.CORREO, '^[^@ ]+@[^@ ]+\.[^@ ]+$') THEN
    RAISE_APPLICATION_ERROR(-20526,
      'Ingrese un correo electrónico válido.');
