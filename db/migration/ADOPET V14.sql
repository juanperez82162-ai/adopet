    END;

    IF NOT REGEXP_LIKE(p_nombre, v_patron) THEN
      RAISE_APPLICATION_ERROR(-20952,
        p_tabla || ': el nombre "' || p_nombre || '" tiene un formato no permitido.');
    END IF;
  END validar_nombre;

