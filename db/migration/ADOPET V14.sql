      'Esta solicitud ya recibió su única prórroga de 21 días y no puede extenderse de nuevo.');

  ELSE
    -- Primera y única prórroga
    UPDATE SOLICITUDES_ADOPCION
       SET FECHA_VENCIMIENTO = FECHA_VENCIMIENTO + 21,
           OBSERVACIONES     = SUBSTR(c_marca || '. ' || NVL(OBSERVACIONES, ''), 1, 500)
     WHERE ID_SOLICITUD = P_ID_SOLICITUD;
  END IF;
