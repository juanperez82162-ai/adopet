set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADOPET"."PRC_CAMBIAR_ESTADO_TIPO_VIVIENDA" (
  p_id      IN  NUMBER   DEFAULT NULL,
  p_nombre  IN  VARCHAR2 DEFAULT NULL,
  p_accion  IN  VARCHAR2 DEFAULT 'ALTERNAR',   -- ALTERNAR | ACTIVAR | DESACTIVAR
  p_mensaje OUT VARCHAR2
) IS
  v_id      TIPOS_VIVIENDA.ID_TIPO_VIVIENDA%TYPE;
  v_nombre  TIPOS_VIVIENDA.NOMBRE%TYPE;
  v_activo  TIPOS_VIVIENDA.ACTIVO%TYPE;
  v_nuevo   TIPOS_VIVIENDA.ACTIVO%TYPE;
  v_accion  VARCHAR2(20) := UPPER(TRIM(NVL(p_accion, 'ALTERNAR')));
BEGIN
  -- 1. Debe venir exactamente uno: id o nombre
  IF (p_id IS NULL AND p_nombre IS NULL)
     OR (p_id IS NOT NULL AND p_nombre IS NOT NULL) THEN
    RAISE_APPLICATION_ERROR(-20990,
      'TIPOS_VIVIENDA: indique el id o el nombre, pero no ambos ni ninguno.');
  END IF;

  IF v_accion NOT IN ('ALTERNAR', 'ACTIVAR', 'DESACTIVAR') THEN
    RAISE_APPLICATION_ERROR(-20991,
      'TIPOS_VIVIENDA: la acción debe ser ALTERNAR, ACTIVAR o DESACTIVAR.');
  END IF;

  -- 2. Buscar la fila (FOR UPDATE la bloquea mientras decidimos)
  BEGIN
    IF p_id IS NOT NULL THEN
      SELECT ID_TIPO_VIVIENDA, NOMBRE, ACTIVO
        INTO v_id, v_nombre, v_activo
        FROM TIPOS_VIVIENDA
       WHERE ID_TIPO_VIVIENDA = p_id
         FOR UPDATE;
    ELSE
      SELECT ID_TIPO_VIVIENDA, NOMBRE, ACTIVO
        INTO v_id, v_nombre, v_activo
        FROM TIPOS_VIVIENDA
       WHERE UPPER(TRIM(NOMBRE)) = UPPER(TRIM(p_nombre))
         FOR UPDATE;
    END IF;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20992,
        'TIPOS_VIVIENDA: no existe un tipo de vivienda con ese ' ||
        CASE WHEN p_id IS NOT NULL THEN 'id.' ELSE 'nombre.' END);
    WHEN TOO_MANY_ROWS THEN
      RAISE_APPLICATION_ERROR(-20994,
        'TIPOS_VIVIENDA: el nombre coincide con más de un registro; use el id.');
  END;

  -- 3. Decidir el nuevo estado
  v_nuevo := CASE v_accion
               WHEN 'ACTIVAR'    THEN 'S'
               WHEN 'DESACTIVAR' THEN 'N'
               ELSE CASE v_activo WHEN 'S' THEN 'N' ELSE 'S' END
             END;

  -- 4. Si no hay cambio, solo informar
  IF v_nuevo = v_activo THEN
    p_mensaje := 'El tipo de vivienda "' || v_nombre || '" (id ' || v_id ||
                 ') ya estaba ' ||
                 CASE v_activo WHEN 'S' THEN 'activo.' ELSE 'desactivado.' END;
  ELSE
    UPDATE TIPOS_VIVIENDA
       SET ACTIVO = v_nuevo           -- aquí se dispara el trigger
     WHERE ID_TIPO_VIVIENDA = v_id;

    p_mensaje := 'El tipo de vivienda "' || v_nombre || '" (id ' || v_id ||
                 CASE v_nuevo
                   WHEN 'N' THEN ') fue desactivado recién.'
                   ELSE          ') fue reactivado.'
                 END;
  END IF;

  DBMS_OUTPUT.PUT_LINE(p_mensaje);
  -- Sin COMMIT: el que llama decide confirmar o deshacer.
END PRC_CAMBIAR_ESTADO_TIPO_VIVIENDA;

