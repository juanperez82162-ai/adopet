  PROCEDURE validar_nombre (p_tabla  IN VARCHAR2,
                            p_nombre IN VARCHAR2,
                            p_estilo IN VARCHAR2,
                            p_min    IN NUMBER,
                            p_max    IN NUMBER) IS
    v_patron VARCHAR2(200);
  BEGIN
    IF p_nombre IS NULL OR LENGTH(p_nombre) < p_min THEN
      RAISE_APPLICATION_ERROR(-20950,
        p_tabla || ': el nombre es obligatorio y debe tener al menos ' || p_min || ' caracteres.');
