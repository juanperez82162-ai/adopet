     OR NOT REGEXP_LIKE(:NEW.DOCUMENTO, '^[A-Z0-9]{5,20}$') THEN
    RAISE_APPLICATION_ERROR(-20521,
      'El documento debe tener entre 5 y 20 caracteres alfanuméricos.');
  END IF;

  -- 3. Nombres y apellidos (paquete)
  PKG_VALIDACIONES.validar_nombre_persona('USUARIOS', 'PRIMER_NOMBRE',    :NEW.PRIMER_NOMBRE);
  PKG_VALIDACIONES.validar_nombre_persona('USUARIOS', 'SEGUNDO_NOMBRE',   :NEW.SEGUNDO_NOMBRE,   'N');
  PKG_VALIDACIONES.validar_nombre_persona('USUARIOS', 'PRIMER_APELLIDO',  :NEW.PRIMER_APELLIDO);
  PKG_VALIDACIONES.validar_nombre_persona('USUARIOS', 'SEGUNDO_APELLIDO', :NEW.SEGUNDO_APELLIDO, 'N');

  -- 4. Contacto (reglas propias)
  IF :NEW.CORREO IS NULL
     OR NOT REGEXP_LIKE(:NEW.CORREO, '^[^@ ]+@[^@ ]+\.[^@ ]+$') THEN
    RAISE_APPLICATION_ERROR(-20526,
      'Ingrese un correo electrónico válido.');
  END IF;

  IF :NEW.TELEFONO IS NULL
     OR NOT REGEXP_LIKE(:NEW.TELEFONO, '^(3[0-9]{9}|60[0-9]{8})$') THEN
    RAISE_APPLICATION_ERROR(-20527,
      'El teléfono debe tener un formato colombiano válido.');
  END IF;

  IF :NEW.DIRECCION IS NULL THEN
    RAISE_APPLICATION_ERROR(-20528,
      'La dirección es obligatoria.');
  END IF;

  -- 5. Activo (paquete)
  PKG_VALIDACIONES.validar_sn('USUARIOS', 'ACTIVO', :NEW.ACTIVO);

  -- 6. Mayoría de edad (regla propia: ningún CHECK puede usar SYSDATE)
  IF :NEW.FECHA_NACIMIENTO IS NULL THEN
    RAISE_APPLICATION_ERROR(-20530,
      'La fecha de nacimiento es obligatoria.');
  END IF;

  IF :NEW.FECHA_NACIMIENTO > ADD_MONTHS(TRUNC(SYSDATE), -216) THEN
    RAISE_APPLICATION_ERROR(-20531,
      'Debes ser mayor de 18 años para registrarte.');
  END IF;

  -- 7. Fecha de registro (paquete)
  IF :NEW.FECHA_REGISTRO IS NULL THEN
    :NEW.FECHA_REGISTRO := SYSDATE;
  END IF;

  PKG_VALIDACIONES.validar_fecha_no_futura('USUARIOS', 'FECHA_REGISTRO', :NEW.FECHA_REGISTRO);
END;

