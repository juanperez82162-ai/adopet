      WHEN 'CIUDADES'             THEN m('ID_CIUDAD',            'NOMBRE');
      WHEN 'ESPECIES'             THEN m('ID_ESPECIE',           'NOMBRE');
      WHEN 'RAZAS'                THEN m('ID_RAZA',              'NOMBRE');
      WHEN 'ETAPAS_SEGUIMIENTO'   THEN m('ID_ETAPA',             'NOMBRE');
      WHEN 'MASCOTAS'             THEN m('ID_MASCOTA',           'NOMBRE');
      WHEN 'NIVELES_ENERGIA'      THEN m('ID_NIVEL_ENERGIA',     'NOMBRE');
      WHEN 'OPCIONES_CHECKPOINT'  THEN m('ID_OPCION',            'TEXTO');
      WHEN 'PREGUNTAS_CHECKPOINT' THEN m('ID_PREGUNTA',          'TEXTO');
      WHEN 'OPCIONES_MENU'        THEN m('ID_OPCION_MENU',       'NOMBRE_OPCION');
      WHEN 'PERFILES'             THEN m('ID_PERFIL',            'NOMBRE_PERFIL');
      WHEN 'ROLES'                THEN m('ID_ROL',               'NOMBRE_ROL');
