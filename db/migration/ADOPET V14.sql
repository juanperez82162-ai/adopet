COMPOUND TRIGGER

  c_marca CONSTANT VARCHAR2(30) := 'PRORROGA_21_DIAS_OTORGADA';

  TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  g_ids t_ids;

  -- Si la prórroga ya estaba marcada y el nuevo texto la pierde, se restituye
  BEFORE EACH ROW IS
  BEGIN
    IF INSTR(UPPER(NVL(:OLD.OBSERVACIONES, ' ')), c_marca) > 0
       AND INSTR(UPPER(NVL(:NEW.OBSERVACIONES, ' ')), c_marca) = 0 THEN
      :NEW.OBSERVACIONES := SUBSTR(c_marca || '. ' || NVL(:NEW.OBSERVACIONES, ''), 1, 500);
    END IF;
  END BEFORE EACH ROW;

  -- Detecta una nueva marca "CONTACTO REGISTRADO:" (sin distinguir mayúsculas)
  AFTER EACH ROW IS
  BEGIN
    IF NVL(REGEXP_COUNT(:NEW.OBSERVACIONES, 'CONTACTO REGISTRADO:', 1, 'i'), 0)
     > NVL(REGEXP_COUNT(:OLD.OBSERVACIONES, 'CONTACTO REGISTRADO:', 1, 'i'), 0) THEN
      g_ids(g_ids.COUNT + 1) := :NEW.ID_SOLICITUD;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    FOR i IN 1 .. g_ids.COUNT LOOP
      PR_GESTIONAR_CONTACTO_SOLICITUD(g_ids(i));
    END LOOP;
  END AFTER STATEMENT;

END TRG_SOL_CONTACTO_PRORROGA;

