  COMPATIBLE_NINOS              CHAR(1)        NOT NULL,
  COMPATIBLE_OTRAS_MASCOTAS     CHAR(1)        NOT NULL,
  TIENE_NECESIDADES_ESPECIALES  CHAR(1)        NOT NULL,
  DESCRIPCION_NECESIDADES       VARCHAR2(500),
  FECHA_INGRESO                 DATE           DEFAULT SYSDATE NOT NULL,
  FECHA_SALIDA                  DATE,
  ID_ESTADO_MASCOTA             NUMBER         DEFAULT 1 NOT NULL,
  ACTIVO                        CHAR(1)        DEFAULT 'S' NOT NULL,
  OBSERVACIONES_ESTADO          VARCHAR2(200),
  CONSTRAINT PK_MASCOTAS          PRIMARY KEY (ID_MASCOTA),
  CONSTRAINT CK_MASCOTA_EDAD      CHECK (EDAD_MESES_INGRESO > 0),
  CONSTRAINT CK_MASCOTA_NINOS     CHECK (COMPATIBLE_NINOS          IN ('S','N')),
  CONSTRAINT CK_MASCOTA_OTRAS     CHECK (COMPATIBLE_OTRAS_MASCOTAS IN ('S','N')),
  CONSTRAINT CK_MASCOTA_NECESID   CHECK (TIENE_NECESIDADES_ESPECIALES IN ('S','N')),
  CONSTRAINT CK_MASCOTA_ACTIVO    CHECK (ACTIVO IN ('S','N')),
  CONSTRAINT CK_MASCOTA_SALIDA    CHECK (FECHA_SALIDA IS NULL OR FECHA_SALIDA >= FECHA_INGRESO),
  CONSTRAINT CK_MASCOTA_INACTIVA  CHECK (ACTIVO = 'S' OR OBSERVACIONES_ESTADO IS NOT NULL)
);

