-- =====================================================================
-- 6. ÍNDICES
-- =====================================================================

-- Correo único sin distinguir mayúsculas de minúsculas.
CREATE UNIQUE INDEX UX_USUARIOS_CORREO_LOWER
  ON USUARIOS (LOWER(CORREO));

-- Una sola foto principal por mascota.
-- Oracle ignora los NULL en índices únicos, así que la restricción
-- solo aplica a las filas marcadas como principales.
CREATE UNIQUE INDEX UX_FOTO_PRINCIPAL_POR_MASCOTA
  ON FOTOS_MASCOTAS (CASE WHEN ES_PRINCIPAL = 'S' THEN ID_MASCOTA END);

-- Un adoptante no puede tener dos trámites vigentes al tiempo.
-- Vigente = ACTIVO (2) o EN_PRUEBA (3). SOLICITUD (1) no cuenta:
-- una persona puede tener varias solicitudes sin formalizar.
CREATE UNIQUE INDEX UX_PROCESO_VIGENTE_POR_USUARIO
  ON SOLICITUDES_ADOPCION (CASE WHEN ID_ESTADO_PROCESO IN (2,3) THEN DOCUMENTO END);

-- Una mascota no puede estar comprometida en dos trámites vigentes.
CREATE UNIQUE INDEX UX_PROCESO_VIGENTE_POR_MASCOTA
  ON SOLICITUDES_ADOPCION (CASE WHEN ID_ESTADO_PROCESO IN (2,3) THEN ID_MASCOTA END);
