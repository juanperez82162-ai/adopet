  ID_MASCOTA                    NUMBER GENERATED AS IDENTITY,
  NOMBRE                        VARCHAR2(50)   NOT NULL,
  ID_RAZA                       NUMBER         NOT NULL,
  EDAD_MESES_INGRESO            NUMBER(3)      NOT NULL,
  ID_TAMANIO                    NUMBER         NOT NULL,
  ID_SEXO                       NUMBER         NOT NULL,
