-- =====================================================================
-- 4. ADOPCIÓN Y SEGUIMIENTO
-- =====================================================================

CREATE TABLE SOLICITUDES_ADOPCION (
  ID_SOLICITUD                              NUMBER GENERATED AS IDENTITY,
  DOCUMENTO                                 VARCHAR2(20)   NOT NULL,
  -- Cuestionario de compatibilidad: se diligencia al crear la fila
  ID_TIPO_VIVIENDA                          NUMBER         NOT NULL,
  TIPO_VIVIENDA_OTRO                        VARCHAR2(100),
  TIENE_ESPACIO_EXTERIOR                    CHAR(1)        NOT NULL,
  ID_TIEMPO_DISPONIBLE                      NUMBER         NOT NULL,
  TIEMPO_DISPONIBLE_OTRO                    VARCHAR2(100),
  EXPERIENCIA_PREVIA                        CHAR(1)        NOT NULL,
  EXPERIENCIA_PREVIA_OBSERVACIONES          VARCHAR2(300),
  DISPUESTO_NECESIDADES_ESPECIALES          CHAR(1)        NOT NULL,
  TIENE_NINOS_HOGAR                         CHAR(1)        NOT NULL,
  TIENE_OTRAS_MASCOTAS_HOGAR                CHAR(1)        NOT NULL,
  TIENE_OTRAS_MASCOTAS_HOGAR_OBSERVACIONES  VARCHAR2(300),
  FECHA_ENVIO                               DATE           DEFAULT SYSDATE NOT NULL,
  -- Proceso formal: lo diligencia el staff si la solicitud avanza
  ID_MASCOTA                                NUMBER,
  DOCUMENTO_STAFF_INICIO                    VARCHAR2(20),
  FECHA_INICIO                              DATE,
  FECHA_VENCIMIENTO                         DATE,
  FECHA_ENTREGA                             DATE,
  ID_ESTADO_PROCESO                         NUMBER         DEFAULT 1 NOT NULL,
  DOCUMENTO_STAFF_CIERRE                    VARCHAR2(20),
  FECHA_RESOLUCION                          DATE,
  OBSERVACIONES                             VARCHAR2(500),
  CONSTRAINT PK_SOLICITUDES_ADOPCION PRIMARY KEY (ID_SOLICITUD),
  CONSTRAINT CK_SOL_EXTERIOR     CHECK (TIENE_ESPACIO_EXTERIOR           IN ('S','N')),
  CONSTRAINT CK_SOL_EXPERIENCIA  CHECK (EXPERIENCIA_PREVIA               IN ('S','N')),
  CONSTRAINT CK_SOL_DISPUESTO    CHECK (DISPUESTO_NECESIDADES_ESPECIALES IN ('S','N')),
  CONSTRAINT CK_SOL_NINOS        CHECK (TIENE_NINOS_HOGAR                IN ('S','N')),
  CONSTRAINT CK_SOL_MASCOTAS     CHECK (TIENE_OTRAS_MASCOTAS_HOGAR       IN ('S','N')),
  CONSTRAINT CK_SOL_VENCE        CHECK (FECHA_VENCIMIENTO IS NULL OR FECHA_VENCIMIENTO > FECHA_INICIO),
  CONSTRAINT CK_SOL_ENTREGA      CHECK (FECHA_ENTREGA IS NULL OR FECHA_ENTREGA >= FECHA_INICIO),
  CONSTRAINT CK_SOL_STAFF_INI    CHECK (DOCUMENTO_STAFF_INICIO IS NULL OR DOCUMENTO_STAFF_INICIO <> DOCUMENTO),
  CONSTRAINT CK_SOL_STAFF_CIE    CHECK (DOCUMENTO_STAFF_CIERRE IS NULL OR DOCUMENTO_STAFF_CIERRE <> DOCUMENTO),
  -- En estado SOLICITUD (1) aun no hay tramite formal; desde ACTIVO (2) si
  CONSTRAINT CK_SOL_FORMALIZADA  CHECK (ID_ESTADO_PROCESO = 1
                                    OR (ID_MASCOTA             IS NOT NULL
                                        AND DOCUMENTO_STAFF_INICIO IS NOT NULL
                                        AND FECHA_INICIO       IS NOT NULL
                                        AND FECHA_VENCIMIENTO  IS NOT NULL))
);

CREATE TABLE SEGUIMIENTOS (
  ID_SEGUIMIENTO     NUMBER GENERATED AS IDENTITY,
  ID_SOLICITUD       NUMBER         NOT NULL,
  ID_ETAPA           NUMBER         NOT NULL,
  FECHA_PROGRAMADA   DATE           NOT NULL,
  FECHA_RESPUESTA    DATE,
  SOLICITA_CONTACTO  CHAR(1),
  COMENTARIO         VARCHAR2(500),
  PUNTAJE            NUMBER(3,2),
  ID_SEMAFORO        NUMBER,
  CONSTRAINT PK_SEGUIMIENTOS       PRIMARY KEY (ID_SEGUIMIENTO),
  CONSTRAINT UQ_SEGUIMIENTO_ETAPA  UNIQUE (ID_SOLICITUD, ID_ETAPA),
  CONSTRAINT CK_SEGUIM_CONTACTO    CHECK (SOLICITA_CONTACTO IN ('S','N')),
  CONSTRAINT CK_SEGUIM_RESPONDIDO  CHECK (FECHA_RESPUESTA IS NULL
                                     OR (SOLICITA_CONTACTO IS NOT NULL
                                         AND PUNTAJE       IS NOT NULL
                                         AND ID_SEMAFORO   IS NOT NULL))
);

CREATE TABLE RESPUESTAS_SEGUIMIENTO (
  ID_SEGUIMIENTO  NUMBER  NOT NULL,
  ID_PREGUNTA     NUMBER  NOT NULL,
  ID_OPCION       NUMBER  NOT NULL,
  CONSTRAINT PK_RESPUESTAS_SEGUIMIENTO PRIMARY KEY (ID_SEGUIMIENTO, ID_PREGUNTA)
);

CREATE TABLE NOTIFICACIONES (
  ID_NOTIFICACION       NUMBER GENERATED AS IDENTITY,
  DOCUMENTO             VARCHAR2(20),
  ID_TIPO_NOTIFICACION  NUMBER         NOT NULL,
  MENSAJE               VARCHAR2(255)  NOT NULL,
  ID_SOLICITUD          NUMBER         NOT NULL,
  FECHA_CREACION        DATE           DEFAULT SYSDATE NOT NULL,
  FECHA_LECTURA         DATE,
  CONSTRAINT PK_NOTIFICACIONES PRIMARY KEY (ID_NOTIFICACION),
  CONSTRAINT CK_NOTIF_LECTURA  CHECK (FECHA_LECTURA IS NULL OR FECHA_LECTURA >= FECHA_CREACION)
);


